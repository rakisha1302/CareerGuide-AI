import io
import streamlit as st
import pandas as pd

from reportlab.lib.pagesizes import A4
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer
from reportlab.lib.styles import getSampleStyleSheet
from xml.sax.saxutils import escape

from modules.database import get_interview_history


# Generate PDF interview report
def generate_interview_pdf(row):

    buffer = io.BytesIO()

    document = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=40,
        leftMargin=40,
        topMargin=50,
        bottomMargin=40
    )

    styles = getSampleStyleSheet()
    story = []

    story.append(
        Paragraph("CareerGuide AI", styles["Title"])
    )

    story.append(
        Paragraph(
            "AI Mock Interview Performance Report",
            styles["Heading2"]
        )
    )

    story.append(Spacer(1, 20))

    details = [
        f"<b>Candidate Name:</b> {escape(str(row['Candidate Name']))}",
        f"<b>Target Role:</b> {escape(str(row['Target Role']))}",
        f"<b>Interview Type:</b> {escape(str(row['Interview Type']))}",
        f"<b>Total Questions:</b> {row['Total Questions']}",
        f"<b>Average Score:</b> {row['Average Score']}/10",
        f"<b>Interview Date:</b> {escape(str(row['Interview Date']))}"
    ]

    for detail in details:
        story.append(Paragraph(detail, styles["Normal"]))
        story.append(Spacer(1, 10))

    story.append(Spacer(1, 15))

    story.append(
        Paragraph(
            "AI Feedback and Final Report",
            styles["Heading2"]
        )
    )

    report = escape(
        str(row["Final Report"])
    ).replace("\n", "<br/>")

    story.append(
        Paragraph(report, styles["Normal"])
    )

    story.append(Spacer(1, 30))

    story.append(
        Paragraph(
            "Generated by CareerGuide AI",
            styles["Italic"]
        )
    )

    document.build(story)

    buffer.seek(0)

    return buffer.getvalue()


# Display interview history dashboard
def run_interview_history():

    st.title("📊 Interview History Dashboard")

    st.write(
        "View your previous AI mock interview performances."
    )

    # Retrieve interview records
    records = get_interview_history()

    if not records:
        st.info(
            "No interview history found. Complete a mock interview first."
        )
        return

    # Convert database records into DataFrame
    columns = [
        "ID",
        "Candidate Name",
        "Target Role",
        "Interview Type",
        "Total Questions",
        "Average Score",
        "Interview Date",
        "Final Report"
    ]

    df = pd.DataFrame(records, columns=columns)

    # Performance metrics
    total_interviews = len(df)
    average_score = df["Average Score"].mean()
    best_score = df["Average Score"].max()

    col1, col2, col3 = st.columns(3)

    col1.metric("Total Interviews", total_interviews)
    col2.metric("Average Score", f"{average_score:.1f}/10")
    col3.metric("Best Score", f"{best_score:.1f}/10")

    st.divider()

    # Interview records
    st.subheader("📋 Previous Interview Records")

    display_df = df.drop(
        columns=["Final Report", "ID"]
    )

    st.dataframe(
        display_df,
        use_container_width=True
    )

    # Interview performance chart
    st.divider()

    st.subheader("📈 Interview Performance Trend")

    chart_df = df.copy()

    chart_df["Interview Date"] = pd.to_datetime(
        chart_df["Interview Date"]
    )

    chart_df = chart_df.sort_values("Interview Date")

    chart_df["Interview Number"] = range(
        1, len(chart_df) + 1
    )

    st.line_chart(
        chart_df.set_index("Interview Number")["Average Score"]
    )

    # Interview report details
    st.divider()

    st.subheader("📄 View Interview Reports")

    for _, row in df.iterrows():

        with st.expander(
            f"{row['Candidate Name']} - {row['Target Role']} "
            f"({row['Interview Date']})"
        ):

            st.write(
                "**Interview Type:**",
                row["Interview Type"]
            )

            st.write(
                "**Total Questions:**",
                row["Total Questions"]
            )

            st.write(
                "**Average Score:**",
                f"{row['Average Score']}/10"
            )

            st.write("**Final Report:**")

            st.write(row["Final Report"])

            # Generate PDF for this interview
            pdf_data = generate_interview_pdf(row)

            st.download_button(
                label="📥 Download Interview Report (PDF)",
                data=pdf_data,
                file_name=f"Interview_Report_{row['ID']}.pdf",
                mime="application/pdf",
                key=f"download_report_{row['ID']}"
            )